package com.yandex.divkit.demo.div.drawing;

public class PaintFloat {

  private float startPosX;
  private float startPosY;

  private float startScaleOverPinchDiam;
  private float startScaleXOverPinchWidth;
  private float startScaleYOverPinchHeight;
  private float startAngleMinusPinchAngle;

  public float getStartPosX() {
    return startPosX;
  }

  public void setStartPosX(float startPosX) {
    this.startPosX = startPosX;
  }

  public float getStartPosY() {
    return startPosY;
  }

  public void setStartPosY(float startPosY) {
    this.startPosY = startPosY;
  }

  public float getStartScaleOverPinchDiam() {
    return startScaleOverPinchDiam;
  }

  public void setStartScaleOverPinchDiam(float startScaleOverPinchDiam) {
    this.startScaleOverPinchDiam = startScaleOverPinchDiam;
  }

  public float getStartScaleXOverPinchWidth() {
    return startScaleXOverPinchWidth;
  }

  public void setStartScaleXOverPinchWidth(float startScaleXOverPinchWidth) {
    this.startScaleXOverPinchWidth = startScaleXOverPinchWidth;
  }

  public float getStartScaleYOverPinchHeight() {
    return startScaleYOverPinchHeight;
  }

  public void setStartScaleYOverPinchHeight(float startScaleYOverPinchHeight) {
    this.startScaleYOverPinchHeight = startScaleYOverPinchHeight;
  }

  public float getStartAngleMinusPinchAngle() {
    return startAngleMinusPinchAngle;
  }

  public void setStartAngleMinusPinchAngle(float startAngleMinusPinchAngle) {
    this.startAngleMinusPinchAngle = startAngleMinusPinchAngle;
  }
}
